import { Farm, FloodObservation, GeoPoint } from '../types';
import { calculateGeodesicAreaSqm, calculatePolygonCenter } from './geo';

/**
 * Constructs a deep link to Google Earth Web centered on the coordinates with 3D camera parameters.
 */
export function getGoogleEarthWebUrl(
  center: GeoPoint,
  altitude: number = 250,
  range: number = 1100,
  heading: number = 0,
  tilt: number = 60
): string {
  const lat = center.lat.toFixed(6);
  const lng = center.lng.toFixed(6);
  const h = Math.round(heading % 360);
  const t = Math.min(85, Math.max(0, Math.round(tilt)));
  const a = Math.round(altitude);
  const d = Math.round(range);
  return `https://earth.google.com/web/@${lat},${lng},${a}a,${d}d,35y,${h}h,${t}t,0r`;
}

/**
 * Generates an OGC-compliant KML 2.2 document for Google Earth Pro (Desktop), Google Earth Web, and mobile.
 * Includes extruded polygon styling, cadastral survey data, crop classification, and flood risk overlay.
 */
export function generateGoogleEarthKml(
  farm?: Farm | null,
  polygonPoints?: GeoPoint[],
  floodObservation?: FloodObservation | null
): string {
  const points = polygonPoints && polygonPoints.length >= 3 
    ? polygonPoints 
    : farm?.polygon && farm.polygon.length >= 3 
    ? farm.polygon 
    : [];

  const center = points.length >= 3 ? calculatePolygonCenter(points) : { lat: 29.855, lng: 76.015 };
  const areaSqm = points.length >= 3 ? calculateGeodesicAreaSqm(points) : (farm?.areaSqm || 0);
  const areaAcres = (areaSqm / 4046.86).toFixed(2);
  const farmerName = farm?.farmerName || 'Registered Agricultural Parcel';
  const village = farm?.village || 'Field Boundary';
  const district = farm?.district || 'Agricultural Zone';
  const state = farm?.state || 'India';
  const khasra = farm?.landRecord?.khasraNumber || 'N/A';
  const crop = farm?.cropType ? farm.cropType.toUpperCase() : 'PADDY / RICE';

  // Format farm coordinates for KML (lng,lat,altitude)
  const coordsFormatted = points.length >= 3
    ? [...points, points[0]].map((p) => `${p.lng},${p.lat},15`).join(' ')
    : '';

  // Flood coordinates if present
  let floodKml = '';
  if (floodObservation?.geoJson?.coordinates) {
    try {
      const floodCoords = floodObservation.geoJson.coordinates[0];
      if (Array.isArray(floodCoords)) {
        const ring = floodCoords.map((c: any) => `${c[0]},${c[1]},8`).join(' ');
        floodKml = `
    <Placemark>
      <name>Satellite Radar Flood Extent — ${floodObservation.satelliteSensor}</name>
      <description><![CDATA[
        <div style="font-family: Arial, sans-serif; padding: 6px;">
          <p><b>Sensor:</b> ${floodObservation.satelliteSensor} (${floodObservation.provider})</p>
          <p><b>Observation:</b> ${floodObservation.observationDate}</p>
          <p><b>Resolution:</b> ${floodObservation.resolutionMeters}m ground sampling</p>
        </div>
      ]]></description>
      <styleUrl>#floodPolygonStyle</styleUrl>
      <Polygon>
        <extrude>1</extrude>
        <altitudeMode>relativeToGround</altitudeMode>
        <outerBoundaryIs>
          <LinearRing>
            <coordinates>${ring}</coordinates>
          </LinearRing>
        </outerBoundaryIs>
      </Polygon>
    </Placemark>`;
      }
    } catch (e) {
      console.warn('Error formatting flood KML:', e);
    }
  }

  return `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>KrishiRakshak AI — Google Earth Agricultural Demarcation</name>
    <description>Farm field boundary, cadastral survey, and flood inundation data generated by KrishiRakshak AI.</description>
    
    <Style id="farmPolygonStyle">
      <LineStyle>
        <color>ff10b981</color>
        <width>3</width>
      </LineStyle>
      <PolyStyle>
        <color>7f10b981</color>
        <colorMode>normal</colorMode>
        <fill>1</fill>
        <outline>1</outline>
      </PolyStyle>
    </Style>

    <Style id="floodPolygonStyle">
      <LineStyle>
        <color>ff3b82f6</color>
        <width>2</width>
      </LineStyle>
      <PolyStyle>
        <color>662563eb</color>
        <fill>1</fill>
        <outline>1</outline>
      </PolyStyle>
    </Style>

    <Style id="centroidPinStyle">
      <IconStyle>
        <color>ff10b981</color>
        <scale>1.3</scale>
        <Icon>
          <href>http://maps.google.com/mapfiles/kml/shapes/placemark_circle.png</href>
        </Icon>
      </IconStyle>
    </Style>

    <!-- LookAt default camera for Google Earth -->
    <LookAt>
      <longitude>${center.lng}</longitude>
      <latitude>${center.lat}</latitude>
      <altitude>100</altitude>
      <heading>0</heading>
      <tilt>60</tilt>
      <range>1200</range>
      <altitudeMode>relativeToGround</altitudeMode>
    </LookAt>

    <Placemark>
      <name>${farmerName} — ${village}</name>
      <description><![CDATA[
        <div style="font-family: Arial, sans-serif; font-size: 13px; color: #111827; padding: 8px;">
          <h2 style="margin: 0 0 6px 0; color: #065f46;">🌾 ${farmerName}</h2>
          <table style="border-collapse: collapse; width: 100%;">
            <tr><td style="padding: 3px 0; color: #6b7280;">Village:</td><td><b>${village}</b></td></tr>
            <tr><td style="padding: 3px 0; color: #6b7280;">District:</td><td><b>${district}, ${state}</b></td></tr>
            <tr><td style="padding: 3px 0; color: #6b7280;">Khasra/Survey:</td><td><b>${khasra}</b></td></tr>
            <tr><td style="padding: 3px 0; color: #6b7280;">Crop:</td><td><b>${crop}</b></td></tr>
            <tr><td style="padding: 3px 0; color: #6b7280;">Field Area:</td><td><b>${areaSqm.toLocaleString()} m² (${areaAcres} Acres)</b></td></tr>
            <tr><td style="padding: 3px 0; color: #6b7280;">Verification:</td><td><b style="color: #059669;">Verified (Khasra Matched)</b></td></tr>
          </table>
          <hr style="margin: 8px 0; border: none; border-top: 1px solid #e5e7eb;" />
          <small style="color: #6b7280;">Demarcated on KrishiRakshak AI — PMFBY Integrated</small>
        </div>
      ]]></description>
      <styleUrl>#centroidPinStyle</styleUrl>
      <Point>
        <coordinates>${center.lng},${center.lat},25</coordinates>
      </Point>
    </Placemark>

    ${coordsFormatted ? `
    <Placemark>
      <name>Farm Cadastral Boundary (Khasra ${khasra})</name>
      <description>Extruded boundary polygon for agricultural parcel in ${village}, ${district}.</description>
      <styleUrl>#farmPolygonStyle</styleUrl>
      <Polygon>
        <extrude>1</extrude>
        <altitudeMode>relativeToGround</altitudeMode>
        <outerBoundaryIs>
          <LinearRing>
            <coordinates>${coordsFormatted}</coordinates>
          </LinearRing>
        </outerBoundaryIs>
      </Polygon>
    </Placemark>` : ''}

    ${floodKml}
  </Document>
</kml>`;
}

/**
 * Downloads a string payload as a .kml file.
 */
export function downloadKmlFile(fileName: string, kmlContent: string): void {
  const blob = new Blob([kmlContent], { type: 'application/vnd.google-earth.kml+xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName.endsWith('.kml') ? fileName : `${fileName}.kml`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
